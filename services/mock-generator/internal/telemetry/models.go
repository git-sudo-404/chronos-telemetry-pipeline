package telemetry

import (
	"math/rand"
	"time"

	vehiclev1 "github.com/git-sudo-404/chronos-telemetry-pipeline/services/telemetry-schemas/gen/go/vehicle/v1"
)

// TelemetryEventType defines the type of frame generated by the vehicle actor
type TelemetryEventType int

const (
	TypeGPS TelemetryEventType = iota
	TypeFuel
	TypeBattery
	TypeEngine
	TypeDiagnostic
)

// String conversion helper for header transport formatting down the pipeline
func (t TelemetryEventType) String() string {
	return [...]string{"gps", "fuel", "battery", "engine", "diagnostic"}[t]
}

// VehicleState is a mutable structural matrix owned exclusively by a single Shard Worker thread.
// It contains no locks (sync.Mutex) as concurrency isolation is handled via channel boundaries.
type VehicleState struct {
	// --- ENGINE SCHEDULE & CONTROL LOGIC ---
	VIN            string                           // Unique entity tracking identifier (VIN)
	SequenceNumber uint64                           // Monotonically increasing sequence index per vehicle
	NextEventTimes map[TelemetryEventType]time.Time // Low-overhead schedule tracking array
	EventIntervals map[TelemetryEventType]time.Duration
	SeededRand     *rand.Rand // Localized randomizer instance for reproducible behavior

	// --- GLOBAL RUNTIME PARAMETERS ---
	SchemaVersion       uint32
	Source              string
	IgnitionOn          bool
	IsBuffered          bool
	IsOffline           bool
	OfflineBuffer       []ImmutableSnapshot
	MaxBufferSize       int
	DriftProbabilityPct int
	DriftDurationSec    int

	// --- GPS PHYSICS STATE ---
	Latitude     float64
	Longitude    float64
	AltitudeM    *float64
	SpeedKmh     float64
	HeadingDir   float64
	GpsAccuracyM *float64
	OdometerKm   *float64

	// --- FUEL MATRIX STATE ---
	FuelLevelPct       float64
	FuelRateLph        *float64
	FuelConsumedTotalL *float64

	// --- BATTERY TRANSIT STATE ---
	VoltageV         float64
	CurrentA         *float64
	TemperatureC     *float64
	StateOfChargePct *float64

	// --- DRIVETRAIN RUNTIME STATE ---
	RPM           float64
	CoolantTempC  float64
	EngineLoadPct float64

	// --- DIAGNOSTIC TRIAGE STATE ---
	DiagnosticCode        string
	DiagnosticSeverity    vehiclev1.DiagnosticSeverity
	DiagnosticDescription string
}

// ImmutableSnapshot is a completely read-only snapshot data container emitted across
// shard channel boundaries. Once created, its data frames are entirely immutable.
type ImmutableSnapshot struct {
	EventID        string
	VehicleID      string
	SequenceNumber uint64
	EventType      TelemetryEventType
	Timestamp      time.Time
	IsBuffered     bool
	StateSnapshot  *VehicleState // Holds a cloned read-only context point for marshaling
}
